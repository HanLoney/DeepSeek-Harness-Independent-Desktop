/**
 * Image-generation plugin, node half.
 *
 * Registers one model-facing tool, `generate_image`, that calls an
 * OpenAI-compatible `POST /images/generations` endpoint, commits the returned
 * raster into the durable attachment store, spills a copy into the calling
 * session's workspace, and hands the picture back on BOTH surfaces:
 *
 *   1. TO THE MODEL, as a native `image` content block, whenever the active
 *      route declares `image` input. This is what lets the assistant see what
 *      it just drew and iterate on it. Routes that declare text input only
 *      (`input: [text]`) are the reason this is a capability check and not a
 *      constant: the pi-ai adapter's preflight and the API proxy's image
 *      admission check both reject a request whose history carries an image
 *      block for such a model, so the block is emitted only when the route
 *      accepts it.
 *   2. TO THE BROWSER, through a same-origin `/image-gen/<token>` route that
 *      serves those bytes back. That is what makes the picture self-contained:
 *      it needs no session-authorization handshake and it keeps working after a
 *      restart, because the token is self-describing and the bytes are
 *      content-addressed in the durable store.
 *
 * `presentationMeta` also emits the durable reference, which rides the
 * `tool/result` event's `meta` for a root call (the registry drops `meta` for a
 * nested Code Mode sub-call, so the rendered `image:` token is the fallback).
 *
 * @module dsh-plugin-image-gen
 */
import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import z from '@deepseek-ai/schemastery'
import { defineTool } from '@deepseek-ai/dsh-tools'
import { AttachmentId } from '@deepseek-ai/dsh-attachment'
import { createUserMessage } from '@deepseek-ai/dsh-llm'
import { installSettingsSection, settingsNamespace } from '@deepseek-ai/dsh-settings'

/** Loader entry name (also the client bundle id). */
export const name = 'image-gen'

/** Services this plugin consumes. `settings` is optional and injected lazily. */
export const inject = ['tools', 'attachments', 'credentials', 'webServer']

/** Upstream gateway used when the composition config names none. */
const DEFAULT_BASE_URL = 'https://43.172.5.210:3000/v1'

/** Default image model. `gemini-3.1-flash-image` answers 500 on this gateway. */
const DEFAULT_MODEL = 'gpt-image-2'

/** Sizes the gateway accepts. */
const SIZES = ['512x512', '1024x1024', '1536x1024', '1024x1536']

/** Default requested size. */
const DEFAULT_SIZE = '1024x1024'

/**
 * Ceiling for one generation round trip. The gateway needs 15-45s per image;
 * this tool declares no registry `timeoutMs`, so this is its own bound.
 */
const REQUEST_TIMEOUT_MS = 180_000

/** Same-origin prefix this plugin serves generated bytes under. */
const ROUTE_PREFIX = '/image-gen'

/** Durable settings namespace; also the settings-panel section id. */
export const SETTINGS_NAMESPACE = 'image-gen'

/** Valid credential-store reference; refs permit letters, digits, and underscores only. */
const API_KEY_CREDENTIAL_REF = 'IMAGE_GEN_API_KEY'

/**
 * The user-editable contract, also exported as the plugin `Config` so the
 * composition entry and the settings document validate identically. Every
 * field carries a default, so an empty settings section resolves to the
 * composed entry rather than failing.
 */
export const SettingsSchema = z.object({
  apiKeyEnv: z.string().default('TEST_API_KEY'),
  baseURL: z.string().default(DEFAULT_BASE_URL),
  model: z.string().default(DEFAULT_MODEL),
  size: z.union([...SIZES]).default(DEFAULT_SIZE),
  saveToWorkspace: z.boolean().default(true)
})

/** The loader validates the composition entry with the same contract. */
export const Config = SettingsSchema

/**
 * Coerce any settings-shaped value into the exact fields the tool reads,
 * tolerating a partial or absent section. Applied to every source so a
 * malformed document degrades to defaults instead of throwing per call.
 * @param value - candidate settings object.
 * @returns fully populated, normalized settings.
 */
function normalizeSettings(value) {
  const raw = value !== null && typeof value === 'object' ? value : {}
  const size = SIZES.includes(raw.size) ? raw.size : DEFAULT_SIZE
  const trimmed = String(raw.baseURL ?? DEFAULT_BASE_URL).trim().replace(/\/+$/u, '')
  return {
    apiKeyEnv: String(raw.apiKeyEnv ?? 'TEST_API_KEY').trim() || 'TEST_API_KEY',
    baseURL: trimmed === '' ? DEFAULT_BASE_URL : trimmed,
    model: String(raw.model ?? DEFAULT_MODEL).trim() || DEFAULT_MODEL,
    size,
    saveToWorkspace: raw.saveToWorkspace !== false
  }
}

/**
 * Sniff a raster media type from magic bytes.
 * @param bytes - encoded image bytes.
 * @returns the attachment-store media type for those bytes.
 */
function mediaTypeOf(bytes) {
  if (bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47) return 'image/png'
  if (bytes[0] === 0xff && bytes[1] === 0xd8) return 'image/jpeg'
  if (bytes[0] === 0x47 && bytes[1] === 0x49 && bytes[2] === 0x46) return 'image/gif'
  if (bytes[8] === 0x57 && bytes[9] === 0x45 && bytes[10] === 0x42 && bytes[11] === 0x50) return 'image/webp'
  return 'image/png'
}

/**
 * Combine caller cancellation with this plugin's own deadline.
 * @param signal - the tool execution signal, absent for a non-agent caller.
 * @param timeoutMs - relative deadline in milliseconds.
 * @returns a signal that aborts on either cause.
 */
function withDeadline(signal, timeoutMs) {
  const deadline = AbortSignal.timeout(timeoutMs)
  return signal === undefined ? deadline : AbortSignal.any([signal, deadline])
}

/**
 * Extract the first image payload from an OpenAI-compatible response body.
 * @param body - parsed `POST /images/generations` response.
 * @returns the base64 payload or a remote URL.
 */
function readImagePayload(body) {
  const entry = Array.isArray(body?.data) ? body.data[0] : undefined
  if (entry === undefined || entry === null || typeof entry !== 'object') {
    throw new Error('图片接口的返回里没有 data[0]')
  }
  if (typeof entry.b64_json === 'string' && entry.b64_json !== '') return { base64: entry.b64_json }
  if (typeof entry.url === 'string' && entry.url !== '') return { url: entry.url }
  throw new Error('图片接口的返回里既没有 b64_json 也没有 url')
}

/**
 * Encode one durable reference as a URL-safe token.
 * @param ref - the stored attachment reference.
 * @returns an opaque, self-describing token.
 */
function encodeRef(ref) {
  return Buffer.from(JSON.stringify({
    attachmentId: String(ref.attachmentId),
    mediaType: ref.mediaType,
    bytes: ref.bytes,
    width: ref.width,
    height: ref.height
  }), 'utf8').toString('base64url')
}

/**
 * Decode a token produced by {@link encodeRef}.
 * @param token - the opaque token.
 * @returns the reference, or undefined when the token is malformed.
 */
function decodeRef(token) {
  try {
    const parsed = JSON.parse(Buffer.from(token, 'base64url').toString('utf8'))
    if (parsed === null || typeof parsed !== 'object') return undefined
    if (typeof parsed.attachmentId !== 'string' || parsed.attachmentId === '') return undefined
    if (typeof parsed.mediaType !== 'string') return undefined
    for (const key of ['bytes', 'width', 'height']) {
      if (!Number.isInteger(parsed[key]) || parsed[key] <= 0) return undefined
    }
    return parsed
  } catch {
    return undefined
  }
}

/**
 * Re-brand one stored reference into the durable `ImageBlock` attachment shape.
 * @param ref - the stored attachment reference.
 * @returns the branded attachment reference.
 */
function imageBlockOf(ref) {
  return {
    type: 'image',
    attachment: {
      attachmentId: AttachmentId(String(ref.attachmentId)),
      mediaType: ref.mediaType,
      bytes: ref.bytes,
      width: ref.width,
      height: ref.height,
      ...ref.name === undefined ? {} : { name: ref.name }
    }
  }
}

/**
 * Plugin body: register the `generate_image` tool and its byte-serving route.
 * @param ctx - host-plane plugin context.
 * @param config - optional composition config (`baseURL`, `model`, `apiKeyEnv`, `size`, `saveToWorkspace`).
 */
export function apply(ctx, config) {
  /**
   * Effective settings source. The composition `config` is only the BASE layer:
   * the durable settings document overrides it, and the canonical wiring
   * republishes it when the user saves. Every read goes through `settings()`
   * at call time rather than closing over a snapshot, which is what makes a
   * saved edit apply to the very next generation with no restart.
   */
  let source = () => config
  let current = normalizeSettings(config)

  /** @returns the effective settings for this call. */
  const settings = () => current

  installSettingsSection(ctx, settingsNamespace(SETTINGS_NAMESPACE), SettingsSchema, config ?? {}, {
    setSource: (next) => { source = next },
    onChange: () => {
      current = normalizeSettings(source())
      ctx.logger.info(`image-gen: settings applied (model=${current.model} size=${current.size})`)
    }
  })

  // ── route: serve one generated image back to the browser ───────────────────
  //
  // The same prefix also carries the settings endpoints (`/image-gen/config`).
  // They exist because `dsh-host-apiproxy` gates the generic settings RPC behind
  // a hardcoded `WEB_SETTINGS_NAMESPACES` allowlist, so a plugin cannot expose
  // its own namespace to the browser through `settingsScope` — the proxy answers
  // `settings-not-exposed` regardless of who registered it. These endpoints
  // write through the SAME settings service, so the document, validation, and
  // the live watcher above are shared with every other settings consumer.
  ctx.effect(() => ctx.webServer.register({
    kind: 'prefix',
    path: ROUTE_PREFIX,
    async handler(req, res) {
      /** Send one plain-text status and close. */
      const fail = (status, message) => {
        res.statusCode = status
        res.setHeader('content-type', 'text/plain; charset=utf-8')
        res.end(message)
      }
      /** Send one JSON body. */
      const json = (status, body) => {
        const text = JSON.stringify(body)
        res.statusCode = status
        res.setHeader('content-type', 'application/json; charset=utf-8')
        res.setHeader('cache-control', 'no-store')
        res.end(text)
      }
      if (req.method !== 'GET' && req.method !== 'HEAD' && req.method !== 'POST') return fail(405, '不支持的请求方法')
      const requested = new URL(req.url ?? '/', 'http://localhost').pathname
      const tail = requested.slice(ROUTE_PREFIX.length).replace(/^\/+/u, '')

      // ── settings endpoint ──
      if (tail === 'config') {
        const settingsService = ctx.get('settings')
        if (settingsService === undefined) return json(503, { ok: false, error: '当前部署没有装 settings 服务' })
        if (req.method === 'POST') {
          let body = ''
          for await (const chunk of req) {
            body += chunk
            if (body.length > 64 * 1024) return fail(413, '配置内容过大')
          }
          let patch
          try {
            patch = JSON.parse(body)
          } catch {
            return json(400, { ok: false, error: '配置内容不是合法的 JSON' })
          }
          if (patch === null || typeof patch !== 'object' || Array.isArray(patch)) {
            return json(400, { ok: false, error: '配置内容必须是一个 JSON 对象' })
          }
          // A raw key is accepted only on this write-only path and stored in
          // the credential service, never in settings.yaml or the response.
          const rawApiKey = patch.apiKey
          delete patch.apiKey
          if (rawApiKey !== undefined && (typeof rawApiKey !== 'string' || rawApiKey.trim() === '')) {
            return json(400, { ok: false, error: 'API Key 不能为空' })
          }
          if (rawApiKey !== undefined) {
            try {
              await ctx.credentials.set(API_KEY_CREDENTIAL_REF, rawApiKey.trim())
              patch.apiKeyEnv = API_KEY_CREDENTIAL_REF
            } catch (error) {
              return json(400, { ok: false, error: '保存 API Key 失败：' + String(error?.message ?? error) })
            }
          }
          // Reject unknown keys instead of silently persisting them.
          const known = Object.keys(SettingsSchema({}))
          const unknown = Object.keys(patch).filter((key) => !known.includes(key))
          if (unknown.length > 0) return json(400, { ok: false, error: `未知字段：${unknown.join('、')}` })
          const candidate = { ...settings(), ...patch }
          // Validate through the same schema the settings document uses, so an
          // out-of-range size is refused here rather than at generation time.
          try {
            SettingsSchema(candidate)
          } catch (error) {
            return json(400, { ok: false, error: '取值不合法：' + String(error?.message ?? error) })
          }
          // Persist only the fields the caller actually sent: a key left out of
          // the body keeps inheriting the composition `base`, which is what
          // makes "reset one field back to the deployment's value" possible.
          try {
            await settingsService.update(SETTINGS_NAMESPACE, patch)
          } catch (error) {
            return json(400, { ok: false, error: '保存失败：' + String(error?.message ?? error) })
          }
          // Echo the value just persisted, not `settings()`: the watcher that
          // refreshes it is asynchronous, so reading it here would race and
          // sometimes report the pre-save configuration back to the form.
          return json(200, {
            ok: true,
            value: candidate,
            apiKeyConfigured: rawApiKey !== undefined || (await ctx.credentials.resolve(candidate.apiKeyEnv)) !== undefined,
            file: settingsService.documentPath ?? null
          })
        }
        const currentSettings = settings()
        const credential = await ctx.credentials.resolve(currentSettings.apiKeyEnv)
        return json(200, {
          ok: true,
          value: currentSettings,
          apiKeyConfigured: credential !== undefined && credential.value !== '',
          writable: settingsService.writable === true,
          file: settingsService.documentPath ?? null
        })
      }

      // ── image bytes ──
      if (req.method === 'POST') return fail(405, 'method not allowed')
      if (tail === '') return fail(404, 'missing image token')
      const ref = decodeRef(decodeURIComponent(tail))
      if (ref === undefined) return fail(400, 'malformed image token')
      try {
        const stored = await ctx.attachments.readImage(ref)
        res.statusCode = 200
        res.setHeader('content-type', stored.ref.mediaType)
        res.setHeader('content-length', String(stored.data.byteLength))
        // Content-addressed bytes never change, so the browser may keep them.
        res.setHeader('cache-control', 'private, max-age=31536000, immutable')
        res.end(Buffer.from(stored.data))
      } catch (error) {
        ctx.logger.warn(`image-gen: serving ${ref.attachmentId} failed: ${String(error)}`)
        fail(404, 'image bytes unavailable')
      }
    }
  }), 'image-gen: /image-gen route')

  /**
   * Resolve the bearer token: an ambient process variable first (so an exported
   * key always wins), then the harness credential store. The variable NAME is
   * read live, so re-pointing it in the settings panel takes effect at once.
   * @returns the non-empty secret.
   */
  async function resolveApiKey() {
    const { apiKeyEnv } = settings()
    const ambient = process.env[apiKeyEnv]
    if (typeof ambient === 'string' && ambient !== '') return ambient
    const resolved = await ctx.credentials.resolve(apiKeyEnv)
    if (resolved !== undefined && resolved.value !== '') return resolved.value
    throw new Error(`没有取到凭据 "${apiKeyEnv}" 的值；请在 $DSH_HOME/.credentials.yaml 或环境变量里设置`)
  }

  /**
   * Run one generation or edit round trip and return raw raster bytes.
   * When `images` is non-empty, the OpenAI-compatible edits endpoint receives
   * one multipart `image` part per attachment. With no images, generations
   * keeps the smaller JSON request used by the original tool.
   * @param prompt - text prompt.
   * @param size - requested size literal.
   * @param signal - combined cancellation signal.
   * @param images - durable image attachment references for edit mode.
   * @returns encoded image bytes.
   */
  async function generate(prompt, size, signal, images = []) {
    const { baseURL, model } = settings()
    const apiKey = await resolveApiKey()
    let response
    if (images.length === 0) {
      response = await fetch(`${baseURL}/images/generations`, {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          authorization: `Bearer ${apiKey}`
        },
        body: JSON.stringify({ model, prompt, size, n: 1 }),
        signal
      })
    } else {
      const form = new FormData()
      form.append('model', model)
      form.append('prompt', prompt)
      form.append('size', size)
      form.append('n', '1')
      for (let index = 0; index < images.length; index++) {
        const stored = await ctx.attachments.readImage(images[index], signal)
        const mediaType = stored.ref.mediaType || 'image/png'
        const extension = mediaType.split('/')[1] || 'png'
        form.append('image', new Blob([stored.data], { type: mediaType }), `reference-${index + 1}.${extension}`)
      }
      response = await fetch(`${baseURL}/images/edits`, {
        method: 'POST',
        headers: { authorization: `Bearer ${apiKey}` },
        body: form,
        signal
      })
    }
    if (!response.ok) {
      const detail = await response.text().catch(() => '')
      throw new Error(`图片网关返回 ${response.status}：${detail.slice(0, 400)}`)
    }
    const payload = readImagePayload(await response.json())
    if (payload.base64 !== undefined) {
      return new Uint8Array(Buffer.from(payload.base64, 'base64'))
    }
    const remote = await fetch(payload.url, { signal })
    if (!remote.ok) throw new Error(`下载图片失败，返回 ${remote.status}`)
    return new Uint8Array(await remote.arrayBuffer())
  }

  /**
   * Decide whether the calling route accepts an `image` content block.
   *
   * Mirrors `tool-fs`'s `read_image` gate: resolve the routed model through the
   * `llm` service and check its declared input modalities. A route that
   * declares no `inputModalities` at all is treated as text-only, because the
   * fail-closed direction is to omit the block rather than to send one the
   * adapter would reject.
   *
   * @param exec - the tool execution context.
   * @returns true when the picture may ride model-facing content.
   */
  async function routeAcceptsImage(exec) {
    const routed = exec.agent?.session.requestHeader()?.config
    const provider = routed?.provider ?? exec.agent?.options.provider
    const activeModel = routed?.model ?? exec.agent?.options.model
    const llm = ctx.get('llm')
    if (provider === undefined || activeModel === undefined || llm === undefined) return false
    try {
      const info = await llm.resolveModelInfo(provider, activeModel, exec.signal)
      return Array.isArray(info.inputModalities) && info.inputModalities.includes('image')
    } catch (error) {
      ctx.logger.warn(`image-gen: image-input probe failed, returning text only: ${String(error)}`)
      return false
    }
  }

  ctx.tools.register(defineTool({
    name: 'generate_image',
    description: [
      'Generate a NEW image from a text prompt and show it to the user. If the current user message includes image attachments and asks for reference-based generation or editing, those images are automatically used as references. To edit a previously generated image from an earlier turn, pass its exact opaque `image` token in `images`; the token is printed in the previous tool result. This calls the image edits endpoint.',
      'Use it whenever the user asks for a picture, illustration, logo, poster, wallpaper, icon, or other artwork. Never invent attachment metadata; use current-message attachments automatically or pass a prior generated image token.',
      'Write the prompt in English and describe subject, style, composition, lighting, and palette in detail; it is sent to the image model verbatim.',
      'The call returns where the PNG was saved plus an image token; the picture is displayed to the user automatically, so never paste the token back as a link.',
      'When the current model accepts image input you also receive the generated picture itself, so you can look at it and refine the prompt on a follow-up call.'
    ].join(' '),
    parameters: {
      prompt: {
        type: 'string',
        required: true,
        description: 'What to draw, in rich detail. English works best.'
      },
      size: {
        type: 'string',
        enum: [...SIZES],
        description: `Image geometry: ${SIZES.join(' | ')}. Defaults to ${DEFAULT_SIZE}.`
      },
      filename: {
        type: 'string',
        description: 'Optional base name for the saved PNG (no directory, no extension).'
      },
      images: {
        type: 'array',
        description: 'Optional exact opaque image tokens returned by earlier generate_image calls. Images attached to the current user message are detected automatically; use this only for images from earlier turns.',
        items: { type: 'string' }
      }
    },
    output: {
      schema: {
        type: 'object',
        additionalProperties: false,
        properties: {
          prompt: {
            type: 'string',
            required: true
          },
          model: {
            type: 'string',
            required: true
          },
          size: {
            type: 'string',
            required: true
          },
          file: {
            type: 'string'
          },
          modelSeesImage: {
            type: 'boolean',
            description: 'Whether this route accepts image input, so the raster rides model-facing content beside the text envelope.'
          },
          image: {
            type: 'string',
            required: true
          },
          attachment: {
            type: 'object',
            additionalProperties: false,
            required: true,
            properties: {
              attachmentId: {
                type: 'string',
                required: true
              },
              mediaType: {
                type: 'string',
                required: true
              },
              bytes: {
                type: 'integer',
                required: true
              },
              width: {
                type: 'integer',
                required: true
              },
              height: {
                type: 'integer',
                required: true
              }
            }
          }
        }
      },
      render: (args, value) => {
        const text = {
          type: 'text',
          text: [
            `Generated a ${value.attachment.width}x${value.attachment.height} ${value.model} image for the prompt: ${value.prompt}`,
            ...value.file === undefined ? [] : [`saved to: ${value.file}`],
            `image: ${value.image}`
          ].join('\n')
        }
        // The raster rides beside its envelope only when the active route
        // declared image input; a text-only route would reject the request.
        return value.modelSeesImage === true
          ? [text, imageBlockOf(value.attachment)]
          : [text]
      },
      presentationMeta: (args, value) => ({
        image: value.image,
        prompt: value.prompt,
        model: value.model,
        size: value.size,
        width: value.attachment.width,
        height: value.attachment.height,
        attachmentId: value.attachment.attachmentId,
        ...value.file === undefined ? {} : { file: value.file }
      })
    },
    presentCall: (args) => ({
      card: 'generic',
      title: '生成图片',
      kind: 'other',
      rawInput: {
        prompt: args.prompt,
        ...args.size === undefined ? {} : { size: args.size },
        ...Array.isArray(args.images) && args.images.length > 0 ? { images: args.images.length } : {}
      }
    }),
    async execute(args, exec) {
      // One snapshot per call: a save that lands mid-generation must not make
      // the recorded model disagree with the bytes actually produced.
      const active = settings()
      const prompt = args.prompt.trim()
      if (prompt === '') throw new Error('generate_image requires a non-empty prompt')
      const size = SIZES.includes(args.size) ? args.size : active.size

      const imageTokens = Array.isArray(args.images) ? args.images : []
      if (imageTokens.some((token) => typeof token !== 'string')) throw new Error('images must contain image tokens returned by generate_image')
      const images = imageTokens.map((token) => {
        const ref = decodeRef(token)
        if (ref === undefined) throw new Error('图片引用无效：请传入上一次 generate_image 返回的完整 image token')
        return ref
      })
      // Use actual image blocks from the latest human message as references.
      // The model never needs to reconstruct opaque attachment metadata.
      const history = exec.agent?.session?.deriveMessages?.() ?? []
      const latestHuman = [...history].reverse().find((message) => message.role === 'user' && message.source?.kind === 'user')
      const currentImages = (latestHuman?.content ?? [])
        .filter((block) => block?.type === 'image' && block.attachment)
        .map((block) => block.attachment)
      const explicitIds = new Set(images.map((image) => String(image.attachmentId)))
      for (const ref of currentImages) {
        if (!explicitIds.has(String(ref.attachmentId))) images.push(ref)
      }
      const data = await generate(prompt, size, withDeadline(exec.signal, REQUEST_TIMEOUT_MS), images)

      const digest = createHash('sha256').update(data).digest('hex').slice(0, 12)
      const base = typeof args.filename === 'string' && args.filename.trim() !== ''
        ? args.filename.trim().replace(/[^\w.-]+/gu, '-').replace(/\.png$/iu, '')
        : 'generated'
      const ref = await ctx.attachments.saveImage({
        data,
        mediaType: mediaTypeOf(data),
        name: `${base}-${digest}.png`
      })

      let file
      if (active.saveToWorkspace) {
        const cwd = exec.agent?.session.header.cwd
        if (typeof cwd === 'string' && cwd !== '') {
          try {
            const target = join(cwd, `${base}-${digest}.png`)
            await mkdir(cwd, { recursive: true })
            await writeFile(target, data)
            file = target
          } catch (error) {
            ctx.logger.warn(`image-gen: generated image was not saved to the workspace: ${String(error)}`)
          }
        }
      }

      const modelSeesImage = await routeAcceptsImage(exec)

      // A nested (Code Mode) sub-call drops `meta` by contract, and its render
      // output is folded into the parent's code result; defer the raster as its
      // own user message so the picture still reaches the model, exactly as
      // `tool-fs`'s `read_image` does.
      if (modelSeesImage && exec.parent !== undefined) {
        exec.deferContext(createUserMessage({
          content: [
            { type: 'text', text: `Generated image for the prompt: ${prompt}` },
            imageBlockOf(ref)
          ],
          source: { kind: 'plugin', plugin: 'image-gen' }
        }))
      }

      return {
        prompt,
        model: active.model,
        size,
        modelSeesImage,
        image: encodeRef(ref),
        ...file === undefined ? {} : { file },
        attachment: {
          attachmentId: String(ref.attachmentId),
          mediaType: ref.mediaType,
          bytes: ref.bytes,
          width: ref.width,
          height: ref.height
        }
      }
    }
  }))
}
